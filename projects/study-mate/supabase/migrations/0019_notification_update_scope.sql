-- 0019 — 알림에서 갱신으로 바뀔 수 있는 열 (INV-N5)
-- ═════════════════════════════════════════════════════════════════════════
--
-- 근거 스펙: docs/specs/notifications.md (INV-N5)
--
-- **0002 가 열 단위로 좁힌 표 넷에 알림만 빠져 있었다.** 참여자(상태만)·채팅 참여
-- (마지막 읽은 시각만)·모집글(제목·요약·본문만)·스터디는 그때 좁혔는데, 알림은 그 목록에
-- 없어서 표 전체 갱신이 열린 채로 남았다.
--
-- **접근 정책만으로는 부족하다.** `notifications_update_own` 의 조건은 받는 사람만 보므로,
-- 그 판정을 통과한 갱신은 `type`·`title`·`reference_id` 를 요청이 보낸 값 그대로 바꾼다.
-- 그러면 「거절되었습니다」를 「수락되었습니다」로 고쳐 놓을 수 있다 — 남은 못 보는 자리라
-- 티도 안 난다. 알림은 "그때 이런 일이 있었다"는 사실 기록이고(0001 의 표 주석), 사실
-- 기록이 뒤에서 고쳐지면 그건 기록이 아니라 주장이다.
--
-- **열 단위 갱신 권한은 정책보다 앞에서 판정한다** — SET 절에 허용되지 않은 열이 들어오면
-- 정책을 보기도 전에 거부된다. service_role 은 건드리지 않는다(관리 경로).
--
-- 앱이 알림에 대고 하는 갱신은 읽음 처리뿐이라, 이 좁힘으로 사라지는 기능은 없다.

revoke update on public.notifications from anon, authenticated;

grant update (read_at) on public.notifications to authenticated;

comment on table public.notifications is
  'INV-N5 — 만들어진 알림의 내용은 바뀌지 않는다. 갱신으로 바뀔 수 있는 열은 read_at 하나뿐이고, '
  '그 강제는 정책이 아니라 열 단위 갱신 권한이 한다(정책의 with check 는 받는 사람만 본다). '
  'INV-N2 — 삽입 정책이 없는 것도 빠뜨린 것이 아니라 계약이다: 알림은 사람이 만드는 것이 아니라 '
  '참가 사건에 붙은 트리거가 만든다.';

-- 0008 — 「마감 임박순」의 순위 키
--
-- 0007 이 이 정렬을 실제로 돌게 만들자 다음 것이 드러났다: 날짜 오름차순 하나뿐이라
-- **가장 오래전에 지난 마감일이 1쪽 맨 위**에 온다. 화면 목록 문서(docs/IA.md)는 이 정렬을
-- "그 날짜가 가까운 순서"라고 정했는데, 지난 날짜는 오늘에서 가장 먼 쪽이다.
-- 시드 데이터의 마감일이 전부 미래라 0007 의 실측에서는 드러날 수 없었다.
--
-- **모집 상태는 건드리지 않는다.** 2026-09-05 결정으로 마감일은 모집 상태(INV-P6)에
-- 들어가지 않는다 — 모집을 닫는 것은 호스트이고(`closed_at`), 마감일은 호스트가 적어 둔
-- 목표에 가깝다. 여기서 정하는 것은 목록에 보이는 **순서**뿐이고, 지난 마감일의 스터디는
-- 그대로 「모집중」이며 신청 버튼도 그대로 눌린다.
--
-- **키를 하나로 만든 이유.** 처음에는 구간(0/1/2) 컬럼과 날짜 컬럼 둘로 정렬했다. 그러면
-- 「지났다」 구간 안이 날짜 오름차순이 되어 6년 전에 끝난 모집이 지난주에 끝난 모집보다
-- 위에 온다. PostgREST 는 키마다 방향이 하나씩이라 그 구간만 뒤집을 수 없는데, 그 제약은
-- 키를 나눴기 때문에 생긴 것이다. 하나의 정수로 합치면 세 덩어리의 순서도, 각 덩어리 안의
-- 방향도 이 함수가 정한다. 덤으로 정렬 키가 하나가 되어 행마다 도는 스터디 조회가 둘에서
-- 하나로 준다.
--
-- 값의 구간 — 겹치지 않는 것을 `least` 가 보장한다(상수를 서로 믿게 두지 않는다):
--   [      0 ..  999999] 아직 안 지난 마감일. 오늘이 0, 가까운 것이 앞
--   2000000              기한 없음
--   [2000002 .. 2999999] 지난 마감일. **최근에 지난 것이 앞**
--                        (어제가 2000002 다 — else 가지는 차가 1 이상이라 2000001 은 안 나온다)
--
-- **0009 가 이 함수를 덮어쓴다.** 무한한 날짜에서 뺄셈이 죽는 것을 그때 막았다. 위 근거는
-- 그대로 유효하고, 도는 본체는 0009 에 있다.
--
-- 0007 과 같은 이유로 `security definer` 가 아니다. 스터디를 직접 읽지 않고 0007 의 함수를
-- 부르므로, "모집글이 보이는 사람은 그 스터디도 보인다"는 판단이 0007 한 자리에만 남는다.
-- 그 전제가 깨지면(비공개 스터디 등) 이 함수는 값을 못 읽어 「기한 없음」 쪽으로 틀린다 —
-- 정보가 새는 방향이 아니다.
--
-- **"오늘"은 데이터베이스 서버의 날짜다**(`current_date`). 화면의 `daysUntil` 도 서버에서
-- 도는 Node 의 날짜를 쓰므로 배포 환경에서 둘은 같은 시간대를 본다. 한국 시간으로 고정할
-- 것인지는 아직 정하지 않았다(백로그).
create or replace function public.study_deadline_rank(public.posts) returns integer
language sql stable set search_path = '' as $fn$
  select case
           when u.d is null            then 2000000
           when u.d >= current_date    then least(u.d - current_date, 999999)
           else                             2000001 + least(current_date - u.d, 999998)
         end
  from (select public.study_recruit_until($1) as d) u;
$fn$;

comment on function public.study_deadline_rank(public.posts) is
  '「마감 임박순」의 순위: 0..999999 안 지난 마감일(가까운 것부터) · 2000000 기한 없음 · 2000001.. 지난 마감일(최근에 지난 것부터). 모집 상태가 아니라 목록 순서만 정한다 — INV-P6 은 마감일을 보지 않는다.';

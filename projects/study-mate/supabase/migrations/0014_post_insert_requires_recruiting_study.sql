-- 0014 — 모집글은 「모집 중」인 스터디에만 붙는다 (INV-Z14)
-- ═════════════════════════════════════════════════════════════════════════
--
-- **두 가지가 한 줄로 닫힌다.**
--
-- ① INV-Z10 은 "지워진 것으로 표시된 스터디는 새로운 쓰기를 받지 않는다 — 새 신청도,
--    새 수락도, **새 모집글도**" 이고 강제 위치를 데이터베이스로 정했는데, 모집글 삽입
--    경로만 비어 있었다. `posts_insert_author` 가 보는 것은 작성자와 호스트 두 조건뿐이고,
--    `private.is_study_host` 는 `deleted_at` 을 아예 안 본다. 그래서 호스트는 자기가 지운
--    스터디에도 모집글을 넣을 수 있었다(2026-09-06 리뷰어 셋이 독립적으로 지적).
--
-- ② 마감된 스터디는 아무도 정한 적이 없었다. 2026-09-06 에 사람이 정했다 —
--    **화면에 「모집중」으로 보이는 상태에서만 새 모집글을 쓸 수 있다.**
--
-- 그래서 판정을 새로 만들지 않고 **화면이 「모집중」 배지를 그릴 때 쓰는 것과 같은 조건**을
-- 부른다. `private.study_is_recruiting` 은 `public.recruiting(studies)` 계산 컬럼과 조건이
-- 같다(닫히지 않음 · 지워지지 않음 · 정원이 안 참). 조건을 여기서 다시 적으면 두 벌이 되어
-- 한쪽만 고쳐지는 날 **화면에는 「마감」인데 글은 써지는** 상태가 조용히 만들어진다.
--
-- 정원이 찼다가 한 명이 나가면 다시 쓸 수 있게 된다. 그것이 「모집중」의 뜻이고,
-- 화면이 그렇게 보여 주므로 규칙과 화면이 어긋나지 않는다.

drop policy if exists posts_insert_author on public.posts;
create policy posts_insert_author on public.posts for insert
with check (
  author_id = (select auth.uid())
  and private.is_study_host(study_id, (select auth.uid()))
  and private.study_is_recruiting(study_id)
);

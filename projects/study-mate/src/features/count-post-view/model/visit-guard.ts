// 같은 방문에서 두 번 세지 않게 하는 가드. 근거 스펙: docs/specs/post-view-count.md (INV-V1)
//
// **`sessionStorage` 를 안 쓴다.** 처음에 그걸로 만들었다가 실측에서 걸렸다 — 세션 저장소는
// **새로고침을 넘어 살아남아서**, 새로고침해도 조회수가 안 오른다. 스펙이 정한 「방문」의
// 경계는 그것보다 좁다: 이 페이지가 로드돼 있는 동안이다.
//
// 그래서 기억은 이 모듈 안에만 둔다. 새로고침하면 모듈이 새로 만들어지므로 기억도 사라지고,
// 화면 안에서 몇 번을 다시 그리든 기억은 남는다 — 그 둘이 정확히 INV-V1 이 요구하는 경계다.
//
// **왜 순수 함수로 떼어 놓았나**: 화면 안에 두면 「가드를 부르기 전에 세우는가」를 확인할
// 방법이 브라우저를 여는 것밖에 없다. 여기 있으면 기억을 직접 넣어 물을 수 있다.

/** 이 페이지가 로드돼 있는 동안의 기억. 새로고침하면 사라진다. */
const 이번페이지에서_본_글 = new Set<string>();

/**
 * 이 방문에서 이 글을 처음 여는가. **처음이면 그 자리에서 기록까지 남긴다** — 묻는 것과
 * 남기는 것을 나누면 그 사이에 두 번째 호출이 끼어든다.
 *
 * 개발 모드는 화면을 일부러 두 번 실행해서 정리되지 않는 부작용을 드러낸다. 그 두 실행은
 * 거의 동시에 오므로, 기록을 **참을 돌려주기 전에** 남기지 않으면 둘 다 「처음」으로 읽는다.
 *
 * `기억` 을 밖에서 넣을 수 있는 것은 검사를 위해서다. 화면은 인자 없이 부른다.
 */
export function 처음인가(postId: string, 기억: Set<string> = 이번페이지에서_본_글): boolean {
  if (기억.has(postId)) return false;
  기억.add(postId);
  return true;
}

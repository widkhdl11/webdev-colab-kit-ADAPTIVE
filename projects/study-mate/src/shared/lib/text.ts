/**
 * 사람이 쓴 글자를 저장하기 전에 보는 판정 셋. 근거 스펙:
 * `docs/specs/text-display-integrity.md`(INV-T1 · INV-T2) ·
 * `supabase/migrations/0022_text_display_integrity.sql`.
 *
 * **강제 위치는 데이터베이스이고 여기는 문구를 위한 자리다.** 제약이 거부하면 나오는 것이
 * 영어 원문이라 화면에 그대로 못 내보내고, 덮어쓴 문구가 「잠시 뒤 다시 시도해 주세요」라서
 * **절대 성공하지 않는 요청에 기다리라고 말하게 된다.**
 *
 * **그래서 범위가 데이터베이스와 같아야 한다.** 여기가 더 좁으면 그 틈으로 들어온 값이
 * 다시 위의 반복되는 오류가 되고, 더 넓으면 데이터베이스가 받아 줄 값을 앱이 거절한다.
 * 2026-09-11 까지 실제로 갈라져 있었다 — 제어문자 판정이 두 벌이었고 한쪽만 C1 구역
 * (U+0080–9F)을 안 봤다. 그 대조는 값 목록으로 검사가 한다(통합 검사의 S6b).
 *
 * **이 파일이 `shared/lib` 에 있는 이유**: 판정이 여러 열에 같이 걸리는데 그 열들은 서로
 * 다른 레이어에 산다. 판정을 한쪽에 두면 나머지가 못 쓰고, 각자 쓰면 **범위가 조용히
 * 갈라진다.** 여기 있는 것은 문자 집합과 술어 셋뿐이고 도메인 개념은 없다.
 */

/**
 * 글자 하나를 코드 포인트로 만든다.
 *
 * **정규식 리터럴에 그 글자를 직접 적지 않는다.** 이 파일이 다루는 것이 「보이지 않는
 * 글자」라서, 소스에 박으면 diff 에도 grep 에도 안 보이고 파일을 옮기거나 붙여 넣는 과정에
 * 조용히 사라진다 — 사라져도 판정은 돌아가고 아무도 모른다(2026-09-06 실측).
 */
const 글자 = (cp: number) => String.fromCodePoint(cp);

/** 코드 포인트 범위를 정규식 문자 부류 조각으로. */
const 범위 = (from: number, to: number) => `${글자(from)}-${글자(to)}`;

/**
 * 주변 글자의 순서를 바꾸는 서식 문자 — 유니코드가 `Bidi_Control=Yes` 로 정한 **열한 자**다.
 *
 * U+061C 는 2026-09-11 에 빠뜨렸다가 넣었다. 그 한 자는 제어문자도 공백도 아니고 아래
 * 지우는 집합에도 없어서, **한 글자로 판정 둘을 동시에 지났다.**
 */
const 양방향서식 = new Set(
  [
    0x061c, 0x200e, 0x200f, 0x202a, 0x202b, 0x202c, 0x202d, 0x202e, 0x2066, 0x2067, 0x2068,
    0x2069,
  ].map(글자),
);

/**
 * 지우고 나면 보이는 것이 안 남는 글자들 — **잉크가 없거나 빈 칸으로 그려지는 것 전부**다.
 * 목록은 2026-09-11 에 Chromium 에서 폭을 재서 정했다.
 *
 * `\s` 로 시작하는 이유는 자바스크립트의 공백 집합이 Postgres 의 `[[:space:]]` 와 **거의**
 * 같기 때문이다. 갈리는 자리는 아래에 전부 따로 적는다 — 둘 다에서 지워지면 어느 쪽이
 * 참이든 결과가 같다.
 *
 * **`\s` 와 `[[:space:]]` 의 차이는 양방향으로 있다.** `\s` 에만 있는 것: U+FEFF.
 * `[[:space:]]` 에만 있는 것: U+0085(NEL) · U+001C–001F. 뒤의 넷은 지금 `hasControlChars`
 * 가 따로 덮지만, 언젠가 줄바꿈만 허용하는 입력창이 생기면 그 처리가 여기서 갈린다.
 */
const 보이지않는글자 = new RegExp(
  "[\\s" +
    글자(0x00a0) + // 로케일에 따라 [[:space:]] 에서 빠질 수 있다 — 못 박는다
    글자(0x2007) +
    글자(0x202f) +
    글자(0x061c) + // 아랍 문자 마크 — 폭 0
    글자(0x180e) + // 몽골 모음 구분 — 유니코드 6.3 에서 공백(Zs)에서 서식(Cf)으로 옮겨 갔다
    범위(0x200b, 0x200d) + // 폭 없는 공백 · 비이음 · 이음(ZWJ)
    범위(0x2060, 0x2064) + // 단어 이음 · 보이지 않는 함수 적용/곱/구분/덧셈
    글자(0x2800) + // 점자 빈 칸 — 잉크 없이 폭 9px
    글자(0x115f) + // 초성 채움
    글자(0x1160) + // 중성 채움
    글자(0x3164) + // 한글 채움 — **폭 14px 로 U+3000 과 똑같다.** 한국 서비스에서
    글자(0xffa0) + //   「빈 닉네임」을 만드는 데 가장 흔히 쓰이는 글자다
    글자(0xfeff) + // BOM
    범위(0xe0000, 0xe007f) + // 태그 문자
    "]",
  "gu",
);

/**
 * 데이터베이스의 `[[:cntrl:]]` 와 같은 범위 — U+0000–1F · U+007F · U+0080–9F.
 *
 * 코드 포인트로 세는 이유는 위 `글자` 의 설명과 같다.
 */
export function hasControlChars(text: string): boolean {
  for (const ch of text) {
    const code = ch.codePointAt(0) ?? 0;
    if (code < 0x20 || code === 0x7f || (code >= 0x80 && code <= 0x9f)) return true;
  }
  return false;
}

/**
 * 양방향 서식 문자가 섞였나 (INV-T2).
 *
 * **오른쪽-왼쪽 글자 자체는 안 본다.** 아랍어·히브리어로 된 이름과 제목은 2026-09-11 실측
 * 에서 알림 줄의 낫표 경계를 안 깼다. 막는 것은 주변 글자의 순서를 바꾸는 서식 문자뿐이다.
 *
 * **U+200D(ZWJ)는 여기 없다.** 가족 이모지가 ZWJ 로 이어 붙인 글자라서, 금지하면 정상
 * 메시지가 막힌다. 방향에도 영향이 없다 — ZWJ 의 `Bidi_Class` 는 BN 이라 양방향 알고리즘이
 * 아예 무시한다. ZWJ 는 아래 `hasVisibleContent` 의 지우는 집합에만 있어서, ZWJ 만으로 된
 * 값은 거부되고 이모지 안에 든 ZWJ 는 통과한다.
 */
export function hasBidiFormatting(text: string): boolean {
  for (const ch of text) if (양방향서식.has(ch)) return true;
  return false;
}

/**
 * 보이지 않는 글자를 전부 지우고 나서 남는 것이 있나 (INV-T1).
 *
 * **`trim()` 이 아니다.** `trim()` 은 양끝만 보고, 자바스크립트의 공백 집합은 폭 없는
 * 글자를 포함하지 않는다. 판정이 막으려는 값은 **가운데가 통째로 보이지 않는 값**이다.
 *
 * **결합 부호는 안 지운다 — 이 스펙의 비범위다.** `cafe` + U+0301 은 정상 입력이고
 * (macOS 의 NFD), 지우는 집합에 넣으면 그런 값이 「내용 없음」으로 거부된다.
 * 그 대가로 **결합 부호만으로 된 값은 이 판정을 통과한다**(화면에서는 폭 0px 다).
 * 좁은 자리라 백로그에 있다 — `docs/BACKLOG.md`.
 */
export function hasVisibleContent(text: string): boolean {
  return text.replace(보이지않는글자, "") !== "";
}

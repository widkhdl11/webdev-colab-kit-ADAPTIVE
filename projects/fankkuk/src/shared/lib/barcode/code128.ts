export const CODE128_PATTERNS: readonly string[] = PATTERNS;
const START_B = 104;
const STOP = 106;

/** B 집합 값(공백 32 ~ 물결 126 → 0~94). 그 밖의 글자는 null */
function valueB(ch: string): number | null {
  const c = ch.charCodeAt(0);
  return c >= 32 && c <= 126 ? c - 32 : null;
}

/** 확인 기호 = (시작 값 + Σ 값 × 자리) mod 103 */
export function code128Checksum(values: readonly number[]): number {
  return values.reduce((sum, v, i) => sum + v * (i + 1), START_B) % 103;
}

/**
 * 글자 → 막대 폭 목록(첫 칸이 검은 막대, 번갈아 빈칸). 앞뒤 조용한 영역(빈칸 10칸)은 넣지 않는다 — 그리는 쪽이 여백을 둔다.
 * B 집합 밖 글자가 있으면 null.
 */
export function code128Widths(text: string): number[] | null {
  if (text.length === 0) return null;
  const values: number[] = [];
  for (const ch of text) {
    const v = valueB(ch);
    if (v === null) return null;
    values.push(v);
  }
  const symbols = [START_B, ...values, code128Checksum(values), STOP];
  return symbols.flatMap((s) => Array.from(PATTERNS[s]!, Number));
}

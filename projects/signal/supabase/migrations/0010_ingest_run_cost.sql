-- 하루 요금 상한이 이 실행에 어떻게 걸렸나 (ingest-chaining-budget INV-CB8, 2026-09-22).
--
-- ── 왜 필요한가 ──────────────────────────────────────────────────────────────
-- 상한에 닿으면 본문 긁기·요약·번역·키워드가 멈춘다. 멈춘 사실을 안 남기면
-- **"그날 글이 없었다"와 "상한에 걸렸다"가 리포트에서 같은 모양이 된다** — 둘 다
-- 요약 0건·키워드 0건으로 보인다. 건너뛴 건수는 `budget` 이 이미 들고 있고,
-- 이 칸은 **왜** 건너뛰었나를 말한다.
--
-- 합계를 같이 남기는 이유: 멈춘 시점의 금액이 없으면 "상한이 낮았나, 진짜 이상한
-- 날이었나"를 나중에 가를 수 없다. 상한 금액(`capUsd`)도 같이 넣는다 — 값을 바꾼 날
-- 옛 실행의 판정이 소급해서 달라지면 안 된다.
--
-- ── 왜 컬럼 넷이 아니라 jsonb 인가 ───────────────────────────────────────────
-- 0005 의 `usage`·`sources`·`budget` 과 같은 판단이다: 이 값은 불변식이 아니라 관찰용이고,
-- 칸이 늘 때마다 마이그레이션이 따라오면 안 된다.
--
-- ── 옛 행 ────────────────────────────────────────────────────────────────────
-- null 로 남는다. "상한이 없던 시절"과 "안 걸렸다"는 다르므로 기본값을 채우지 않는다 —
-- 읽는 쪽(row.ts)이 null 을 그대로 null 로 들고 화면이 두 경우를 가를 수 있게 한다.
alter table ingest_run add column if not exists cost jsonb;

comment on column ingest_run.cost is
  '하루 요금 상한 판정 {capUsd, spentUsd, capped, lookupFailed}. null = 상한이 없던 시절의 실행.';

-- ── 왜 표시 칸이 필요한가 ────────────────────────────────────────────────────
-- 키워드 후보는 "아직 키워드가 안 붙은 글"인데, 그것을 `item_tag` 연결 유무로 판정하면
-- **모델이 "짚이는 게 없다"고 답한 글이 영원히 후보로 남는다.** 붙은 게 없으니 다음 주기에
-- 또 뽑히고, 또 물어보고, 또 없다고 답한다 — 같은 질문에 매일 요금이 나간다.
-- 요약(`summary`)이 재시도 신호 노릇을 하는 것과 같은 자리인데, 키워드는 "없음"이 정상
-- 결과라서 값 자체로는 구별이 안 된다. 그래서 시각 칸을 따로 둔다.
--
-- 실패(응답을 못 읽음)와는 다르다: 그쪽은 표시를 안 남기므로 다음 주기에 다시 잡힌다.
alter table public.item
  add column if not exists keywords_at timestamptz;

-- 후보 조회(`keywords_at is null` + 발행시각 내림차순)가 매번 전체를 훑지 않게.
-- 부분 인덱스로 둔다 — 채워진 행은 후보가 아니라 인덱스에 담을 이유가 없다.
create index if not exists item_missing_keywords_idx
  on public.item (published_at desc)
  where keywords_at is null;


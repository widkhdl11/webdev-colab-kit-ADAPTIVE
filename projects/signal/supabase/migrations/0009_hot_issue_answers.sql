-- 핫이슈 판정의 **근거**를 담을 자리 (hot-issue.md INV-G2 · S31, 2026-09-21).
--
-- ── 왜 필요한가 ──────────────────────────────────────────────────────────────
-- 0008 은 중요도(참인 개수)만 저장했다. 그런데 INV-G2 가 질문을 셋으로 나눈 이유가
-- "하나로 뭉쳐 물으면 **어느 질문이 참이어서 뽑혔는지** 사람이 확인할 수 없다"이고,
-- S31 은 "중요도가 저장되고 어느 질문이 참인지도 남는다"를 요구한다.
--
-- 저장하지 않는 동안 남는 것은 `중요도 1` 이라는 숫자뿐이었다. 그 상태로는 첫 2주 표본
-- 검토가 할 일이 없다 — 판정이 헐겁다는 것까지는 보여도 **셋 중 어느 질문을 고쳐야
-- 하는지**를 말할 수 없기 때문이다.
--
-- ── 왜 컬럼 셋이 아니라 jsonb 인가 ───────────────────────────────────────────
-- `ingest_run`(0005)의 `usage`·`sources`·`budget` 과 같은 판단이다. 거기 주석 그대로:
-- "칸마다 컬럼을 만들면 계측 항목이 늘 때마다 마이그레이션이 또 필요하다 —
--  이 값은 불변식이 아니라 관찰용이다."
--
-- 질문 셋은 **고칠 것을 전제로 만든 값이다**(표본 검토의 목적이 그 질문을 고치는 것이다).
-- `변화`·`방향`·`기회` 를 컬럼 이름으로 박으면 질문 하나를 바꿀 때마다 마이그레이션이
-- 따라오고, 옛 컬럼에 남은 값이 무슨 질문의 답이었는지도 흐려진다. jsonb 에 키까지
-- 같이 넣으면 그 행이 **어떤 질문을 받았는지**가 행 안에 남는다.
--
-- 대신 이 칸으로 거르거나 정렬하지 않는다. 그런 판정은 `importance`(0008)가 한다 —
-- 그쪽은 값 범위를 제약으로 막아 두었고, 이 칸은 사람이 읽는 기록이다.
--
-- 모양: {"변화": true, "방향": false, "기회": true}
-- 키는 코드의 `HOT_ISSUE_QUESTIONS` 가 정한다. DB 는 모양을 강제하지 않는다 —
-- 강제하면 질문이 바뀌는 날 이 파일을 또 고쳐야 하고, 그게 위에서 피하려던 바로 그것이다.
alter table public.item
  add column if not exists hot_issue_answers jsonb;

-- 인덱스를 만들지 않는다. 이 칸을 조건으로 찾는 조회가 없다(후보 조회는 `hot_issue_at`,
-- 화면은 `gate` 를 본다). 읽는 것은 표본 검토 스크립트가 전부라 전체 훑기로 충분하다.

-- RLS 는 `item` 의 기존 정책을 그대로 따른다 — 행 단위 정책이라 컬럼이 늘어도 바뀔 것이 없다.
-- 쓰기는 수집이 secret 키로 하고, 읽기는 publishable 키로 열려 있다(0001 과 같다).

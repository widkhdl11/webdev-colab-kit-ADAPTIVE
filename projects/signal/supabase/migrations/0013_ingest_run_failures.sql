-- 실행 하나에서 무엇이 왜 실패했나 (2026-09-27 사용자 요청 — 대시보드의 「그날 처리 결과」).
--
-- ── 왜 필요한가 ──────────────────────────────────────────────────────────────
-- 수집 리포트는 단계마다 실패 이유(`failureReasons`·`error`)를 만들지만 저장할 때 버렸다.
-- 그래서 API 요금이 떨어진 날도 대시보드에는 "요약 0건"으로만 보이고, **왜 0건인지**가
-- Cron 응답 본문(Vercel 로그) 말고는 어디에도 남지 않았다.
--
-- ── 왜 jsonb 인가 ────────────────────────────────────────────────────────────
-- 0005 의 `usage`·`sources`·`budget`, 0010 의 `cost` 와 같은 판단이다: 관찰용 값이고,
-- 단계가 늘 때마다 마이그레이션이 따라오면 안 된다. 모양은 `[{stage, reason}]`.
--
-- ── 옛 행 ────────────────────────────────────────────────────────────────────
-- null 로 남는다. **"실패가 없었다"(빈 배열)와 "그때는 이유를 저장하지 않았다"(null)는 다르다** —
-- 기본값을 채우지 않는다.
alter table ingest_run add column if not exists failures jsonb;

comment on column ingest_run.failures is
  '실패 이유 [{stage, reason}]. 빈 배열 = 실패 없음, null = 이유를 저장하기 전의 실행.';

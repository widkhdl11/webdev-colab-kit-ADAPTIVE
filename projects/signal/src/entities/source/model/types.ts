/** 수집 소스 한 곳. 소식이 어디서 왔는지와, 그 출처를 얼마나 쳐주는지. */

/**
 * 소스의 성격 (content-selection INV-L1).
 * `daily` = 화제성 — 매일 훑는 것. `deep` = 전문적 — 시간 날 때 읽는 것.
 */
export type SourceTier = "daily" | "deep";

/**
 * 공식 발표가 나오는 자리 (content-selection INV-O3 의 "설정").
 *
 * 도메인 문자열 하나로 두지 않는 이유: 하위 도메인과 경로까지 싸잡으면 **사람이 글을 올릴 수
 * 있는 곳까지 확정 "공식 발표"가 된다.** `community.openai.com`(개발자 포럼),
 * `huggingface.co/<사용자>/<모델>` 이 실제로 그렇고, HN 프론트페이지를 거쳐 들어올 수 있다.
 * 그러면 INV-O2 가 막으려던 상태(기계 근거인데 틀림)가 그대로 생긴다.
 */
export interface SubjectSite {
  /** 정확히 이 호스트여야 한다 (`www.` 는 무시). 하위 도메인은 **포함하지 않는다.** */
  host: string;
  /**
   * 이 경로로 시작할 때만 공식으로 본다. 없으면 그 호스트 전체.
   * 호스트 전체를 여는 것은 그 호스트에 그 주체의 글만 있을 때뿐이다.
   */
  pathPrefix?: string;
}

export interface Source {
  /** 항목이 들고 다니는 값. 바뀌면 기존 항목의 출처를 잃으므로 고정이다. */
  id: string;
  /** 화면 메타 줄에 그대로 쓰인다. */
  name: string;
  /**
   * 랭킹 가중치 (ingestion-ranking INV-R2·R4).
   *
   * **항목에 스냅샷으로 복사하지 않는다.** weight 는 소스에 귀속하는 값이라,
   * 여기를 고치면 다음 조회부터 그 소스의 모든 항목 순위가 바로 따라온다.
   * 항목에 박아 두면 설정을 고쳐도 옛 값이 남아 아무 일도 안 일어난다.
   */
  weight: number;
  /** 수집할 피드 주소. 수집기가 읽는다. */
  feedUrl: string;
  /**
   * 층 (INV-L1). 항목이 아니라 소스에 귀속한다 — 항목마다 다르면
   * "어느 소스가 어느 층인가"를 알 수 없어진다.
   */
  tier: SourceTier;
  /**
   * 이 소스의 글에 주제 판정을 걸 것인가 (INV-F4).
   *
   * `false` = 이 피드에는 AI·IT 글만 온다(AI 전용 섹션·회사 공식 블로그).
   * 답이 정해진 질문에 건당 3.8초와 요금을 쓸 이유가 없다.
   * `true` = 주제가 섞인다(Hacker News·GeekNews). 투구게·칵테일 레시피가 여기서 들어왔다.
   *
   * **선택이 아니라 필수 필드다.** 빠뜨리면 컴파일이 안 된다 — 기본값을 두면
   * 새 소스를 넣을 때 아무도 이 질문에 답하지 않고, 기본값이 `false` 면 필터가
   * 조용히 안 걸리고 `true` 면 요금이 조용히 나간다. 둘 다 나중에야 드러난다.
   */
  needsTopicCheck: boolean;
  /**
   * 이 피드가 **타임존 없이** 주는 시각을 어느 시간대의 벽시계값으로 읽을지 (INV-C5).
   *
   * 안 주면 UTC 로 읽는다 — 14곳 중 12곳은 타임존을 제대로 붙이므로 이 필드가 필요 없다
   * (실측 2026-08-26). 존이 **적혀 있는** 값에는 영향이 없다: 적힌 존이 언제나 우선이다.
   *
   * 왜 소스별인가: 아이타임스·인공지능신문이 `2026-08-26 17:50:06` 처럼 한국시간 벽시계값을
   * 존 없이 준다. 전부 UTC 로 읽으면 이 두 곳만 9시간 미래가 되어 날짜가 하루 밀리고,
   * 랭킹의 나이가 0 이라 피드 맨 위에 고정된다. 그렇다고 전부 KST 로 읽으면 나중에
   * 타임존 없는 **해외** 피드를 추가할 때 그쪽이 조용히 9시간 틀어진다.
   */
  feedTimezone?: string;
}

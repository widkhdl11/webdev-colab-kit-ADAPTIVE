const AGENT_TOOL_COUNT_BODY = `
<p>에이전트를 만들다 보면 자연스럽게 도구를 하나씩 더 붙이게 된다. 검색이 필요하니 검색 도구, 파일을 읽어야 하니 읽기 도구, 그리고 어느새 목록이 화면을 넘어간다. 그런데 도구를 붙일 때마다 기대만큼 결과가 좋아지지는 않는다. 오히려 어느 지점을 지나면 엉뚱한 도구를 고르는 일이 늘어난다.</p>

<h2>선택지가 늘면 무슨 일이 생기나</h2>

<p>모델 입장에서 도구 목록은 결국 프롬프트의 일부다. 도구가 스무 개라면 스무 개의 설명이 매 요청마다 함께 들어간다. 문제는 길이만이 아니다. 설명이 서로 비슷하면 경계가 흐려지고, 모델은 그 흐린 경계에서 판단을 내려야 한다.</p>

<ul>
  <li><code>search_docs</code> 와 <code>find_file</code> 처럼 이름만 다르고 하는 일이 겹치는 경우</li>
  <li>같은 대상을 다루는데 인자 모양만 다른 도구가 나란히 있는 경우</li>
  <li>거의 안 쓰이지만 "혹시 몰라서" 남겨둔 도구</li>
</ul>

<p>세 경우 모두 사람에게는 사소해 보이지만, 모델에게는 매번 다시 풀어야 하는 문제로 남는다.</p>

<blockquote>
  <p>도구를 하나 더 만들기 전에, 지금 있는 도구 중 무엇을 지울 수 있는지 먼저 본다. 지울 게 없다면 대개 설명이 부족한 것이지 도구가 부족한 게 아니다.</p>
</blockquote>

<h2>설명은 짧게, 대신 경계를 적는다</h2>

<p>도구 설명을 길게 쓰면 잘 고를 것 같지만, 실제로 도움이 된 건 "이 도구가 무엇을 하지 않는지"를 한 줄 넣는 쪽이었다. 아래처럼 <code>description</code> 에 사용 조건을 명시하면 비슷한 도구 사이의 경계가 생긴다.</p>

<pre><code>{
  name: "search_docs",
  description:
    "사내 문서에서 키워드로 검색한다. " +
    "코드 파일은 다루지 않는다 — 그건 search_code 를 쓴다.",
  input: {
    query: { type: "string" },
    limit: { type: "number", default: 10 }
  }
}</code></pre>

<p>설명을 다듬은 뒤에도 헷갈린다면, 그건 두 도구가 실제로 하나여야 한다는 신호일 수 있다.</p>

<h2>먼저 로그를 본다</h2>

<p>호출 기록을 며칠만 모아보면 자주 쓰이는 도구와 거의 안 쓰이는 도구가 금방 갈린다. 안 쓰이는 쪽은 필요 없는 도구이거나, 필요한데 모델이 못 찾고 있는 도구다. 어느 쪽인지는 실패한 호출을 몇 개 열어보면 대체로 판별된다.</p>

<p>정리하면 순서는 이렇다. 로그로 현황을 보고 → 겹치는 도구를 합치고 → 남은 도구의 설명에 경계를 적는다. 도구를 새로 만드는 건 그다음이다.</p>

<p>관련해서 도구 스키마를 다루는 방식은 <a href="https://modelcontextprotocol.io/">Model Context Protocol 문서</a>에도 비슷한 관점으로 정리되어 있다.</p>
`.trim();

/** 나머지 항목의 본문. 제목·요약·출처만 갈아끼운 같은 뼈대다(더미라는 사실을 숨기지 않는다). */
function genericBody(title: string, summary: string, sourceUrl: string): string {
  return `
<p>${summary}</p>

<h2>무엇이 문제였나</h2>

<p>“${title}”라는 제목으로 정리된 글이다. 처음에는 간단해 보였지만, 실제로 손을 대보니 걸리는 지점이 몇 군데 있었다는 이야기로 시작한다. 대부분의 시간은 만드는 데가 아니라 무엇을 만들지 정하는 데 들어갔다.</p>

<ul>
  <li>기대한 동작과 실제 동작이 어긋나는 지점을 먼저 찾는다</li>
  <li>고치기 전에 <code>재현 조건</code>을 적어둔다 — 적을 수 없으면 아직 이해하지 못한 것이다</li>
  <li>되돌릴 수 있는 크기로 나눠서 바꾼다</li>
</ul>

<blockquote>
  <p>도구를 늘리는 것보다 지금 쓰는 것을 다시 보는 편이 대체로 빨랐다.</p>
</blockquote>

<h2>어떻게 정리했나</h2>

<p>결론부터 적으면, 규칙을 하나 정하고 그 규칙이 깨지는 경우만 따로 처리하는 방식이 가장 오래갔다. 예외를 먼저 나열하면 규칙이 사라진다.</p>

<pre><code>if (!이해했는가) {
  적어본다()   // 적히지 않으면 아직 모르는 것
}</code></pre>

<p>자세한 배경과 수치는 <a href="${sourceUrl}">원문</a>에 정리되어 있다.</p>
`.trim();
}

export function dummyBody(seed: {
  id: string;
  title: string;
  summary: string;
  sourceUrl: string;
}): string {
  if (seed.id === "agent-tool-count") return AGENT_TOOL_COUNT_BODY;
  return genericBody(seed.title, seed.summary, seed.sourceUrl);
}

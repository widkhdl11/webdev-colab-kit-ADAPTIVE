/**
 * 태그명 정규화 — 유일성 판정 하나만 남은 파일.
 *
 * **여기 있던 규칙 기반 태깅을 2026-08-30 에 지웠다** (옛 ingestion-ranking INV-T3).
 * 제목에 `agent` 가 있으면 `에이전트` 를 붙이는 손으로 쓴 키워드 표(`KEYWORDS`)와,
 * 그것을 AI 분류와 합치던 `mergeTags` 였다. 둘 다 **고정 5개 목록 전용**이라
 * 자유 생성(badge-keywords INV-B1)으로 넘어가면서 쓸 자리가 없어졌다.
 *
 * 실측이 그 방식을 뒤집었다: 690건에서 `툴` 은 한 번도 안 나왔고(표에는 있었다),
 * 자유 생성은 107종을 냈다(2026-08-15). 목록을 손으로 정하는 것 자체가 추측이었다.
 */

/**
 * 태그명 정규화 — DB unique(normalized_name) 가 유일성을 판정하는 값이다 (INV-T2).
 *
 * 도메인 규칙이라 여기 둔다. 어댑터에 인라인으로 있으면 `.toLowerCase()` 한 조각을 지워도
 * 아무 테스트가 안 깨지고, 'MCP' 와 'mcp' 가 각각 생겨 필터가 쪼개진다.
 *
 * 자유 생성으로 넘어오면서 이 함수가 **더 중요해졌다** — 예전엔 목록 밖 이름이 애초에
 * 안 들어왔지만, 이제는 모델이 만든 표기를 이 함수 하나가 붙든다.
 */
export function normalizeTagName(name: string): string {
  return (
    name
      // 한글은 같은 글자가 완성형(가)과 조합형(ㄱ+ㅏ) 두 가지 바이트로 온다. 눈으로는 같은데
      // 문자열 비교가 갈리므로, 정규화 없이는 "에이전트" 가 두 행으로 생길 수 있다.
      .normalize("NFC")
      // 하이픈·언더스코어를 공백으로 본다 — `온-디바이스 AI` 와 `온디바이스 AI`,
      // `e-commerce` 와 `e commerce` 가 갈리지 않게. 화면에 쓰는 표시 이름은 원래 표기
      // 그대로 따로 저장하므로(lib/tag-links 의 tagUpsertRows) 하이픈이 사라지지 않는다.
      .replace(/[-_]+/g, " ")
      // 연속 공백은 하나로. 모델 출력에 두 칸이 섞여 오는 일이 실제로 있다.
      .replace(/\s+/g, " ")
      .trim()
      .toLowerCase()
  );
}

/**
 * 달러 추정 비용을 원화로 바꾼다 (2026-08-26).
 *
 * 왜 별도 파일인가: 환율은 요금표(estimate-cost.ts)와 **낡는 속도가 다르다.** 요금은
 * 앤트로픽이 바꿀 때만 움직이고 프로모션 종료일처럼 예고된 날짜가 있지만, 환율은 매일 움직인다.
 * 한 파일에 두면 "이 파일은 언제 손봐야 하나"의 답이 두 개가 된다.
 *
 * **이 값은 자동으로 갱신되지 않는다.** 2026-08-26 확인 시점의 값이고, 화면의 원화 표시는
 * 그날 환율로 계산한 근사치다. 정확한 청구액은 앤트로픽 콘솔의 달러 금액이 기준이다 —
 * 여기 원화는 "대충 얼마인지" 가늠하려고 있는 값이다.
 */
export const USD_TO_KRW = 1383;

/**
 * 달러를 원으로. 원 단위 아래는 반올림한다 — 이 화면에서 1원 미만은 뜻이 없다.
 *
 * 음수는 들어올 자리가 없지만(비용은 0 이상), 들어오면 그대로 음수로 돌려준다 —
 * 여기서 0 으로 접으면 상류의 계산 오류가 화면에서 정상으로 보인다.
 */
export function toKrw(usd: number): number {
  return Math.round(usd * USD_TO_KRW);
}

/** 정규식 문자 클래스 안에 넣을 조각. 쓰는 쪽이 자기 울타리 글자를 이어 붙인다. */
export const UNSAFE_CHAR_CLASS = "\\u0000-\\u001f\\u007f\\u0085\\u2028\\u2029";

/**
 * 울타리 글자를 더해 검사기를 만든다.
 *
 * @param fenceChars 그 자리에서 값을 감싸는 글자들. 정규식 문자 클래스 안에 그대로 들어가므로
 *                   `-`·`]`·`\` 는 넘기지 않는다(지금 쓰는 곳은 백틱과 따옴표뿐이다).
 */
export function unsafeCharTest(fenceChars = ""): RegExp {
  return new RegExp(`[${UNSAFE_CHAR_CLASS}${fenceChars}]`);
}

/**
 * 남의 글을 `<자료>` 로 감싼다 — 모델에 보내는 모든 외부 문자열이 여기를 거친다.
 *
 * 감싸기만 해서는 부족하다 (2026-08-13 보안 리뷰): 자료 안에 `</자료>` 가 들어 있으면
 * **자료가 자기 경계를 닫는다.** 그 뒤 문장은 자료 밖 텍스트로 읽히고, 그러면 지시가 된다.
 *
 * 도달 경로가 짧다: 투고형 소스(GeekNews)에 글을 올리면 → 본문 추출이 그 페이지 HTML 을
 * 통째로 저장하고 → 요약 후보에 들어간다. XSS 가 아니라 내용 위조다 — 요약·핵심 항목·
 * 한국어 제목이 공격자 문장이 되고, `official: true` 를 받으면 "공식 발표라고 함" 표시까지 붙는다.
 * 그 카드는 피드 상단에 앉는다.
 *
 * 막는 방법: 자료 안의 `<자료`·`</자료` 를 **태그가 아닌 글자로 바꾼다.** 이 경계를 닫을 수
 * 있는 문자열은 그것뿐이라 다른 HTML 은 그대로 둔다(모델이 본문 구조를 읽는 데 지장이 없다).
 * `‹`(U+2039)는 태그 파싱에 쓰이지 않는 글자다.
 *
 * 실행마다 다른 nonce 를 붙이는 방법도 있으나 쓰지 않았다 — 이 함수가 순수해야 조립 결과를
 * 테스트가 직접 보고 "자료 밖에 남는 글이 없다"를 단언할 수 있다.
 */
const CLOSER = /<(\/?)\s*자료/g;

/** 자료 안에서 경계를 닫을 수 있는 문자열을 무해화한다. */
export function neutralizeFence(text: string): string {
  return text.replace(CLOSER, "‹$1자료");
}

/** 외부 문자열을 `<자료 종류="...">` 로 감싼다. 안쪽은 반드시 무해화를 거친다. */
export function fenceData(kind: string, text: string): string {
  return `<자료 종류="${kind}">\n${neutralizeFence(text)}\n</자료>`;
}

/**
 * 수집 한 바퀴가 **얼마나 하는지**를 정하는 숫자들.
 *
 * 왜 한 파일에 모으나 (2026-08-13 리뷰): 이 값들이 `api/ports.ts` 안에 있었는데,
 * 그 파일은 `server-only` 라 유닛 테스트가 한 번도 로드하지 않는다. 그래서
 * `ENRICH_POOL` 을 100 → 10 으로 바꿔도 450개가 전부 green 이었다 —
 * 그렇게 바꾸면 "점수로 고른다"가 항등 함수가 되어 이번에 고친 버그로 그대로 돌아간다.
 *
 * 여기 있는 값은 전부 `budgets.test.ts` 가 값 자체를 못 박는다. 바꾸려면 테스트도
 * 같이 바꿔야 하고, 그게 곧 "사람이 한 번 더 판단한다"는 뜻이다.
 */

/**
 * 한 주기에 요약·번역할 최대 건수.
 *
 * 첫 수집에서 수백 건을 한꺼번에 부르면 비용·시간이 튄다. 밀린 것은 다음 주기가 가져간다.
 */
export const ENRICH_BATCH = 10;

/**
 * 요약 후보를 고를 때 **점수를 매겨 볼 범위**.
 *
 * ENRICH_BATCH 만큼만 받아서 고르면 고를 것이 없다(받은 게 곧 답이 된다).
 * 넓게 받아 점수로 추리되, 본문은 이 단계에서 안 받는다 — 한 건이 2만 자라
 * 100건이면 응답이 수 MB 가 된다. 세 칸(id·발행시각·소스)만 받으므로 500건이어도 작다.
 *
 * 왜 100 이 아니라 500 인가: 자르는 기준(발행시각)과 고르는 기준(점수)이 다르면,
 * 점수로는 이겼을 항목이 풀 경계에서 먼저 탈락한다. 2026-08-13 기준 후보가 약 395건
 * (526건 중 요약 131건)이라 100 은 매 주기 실제로 자르고 있었다. 500 이면 경계 밖은
 * 전부 반감기 18시간으로 감쇠가 0 에 가까운 옛 글이라 점수로도 어차피 못 든다.
 */
export const ENRICH_POOL = 500;

/**
 * 한 주기에 **한 소스가 가져갈 수 있는 최대 칸수**.
 *
 * 점수순 선정만으로는 부족하다 — 자주 올리고 weight 도 높은 소스 하나가 그날 신규분만으로
 * 예산을 다 채운다(2026-08-13 리뷰: GeekNews weight 1.5 × 하루 수십 건). 그러면 weight 가
 * 조금 낮은 매체는 당일에도 밀리고, 다음 주기엔 감쇠로 더 떨어져 **영영 번역·요약을 못 받는다.**
 * 화면에는 그 매체 글이 영어 제목 카드로 고정된다.
 *
 * 상한에 걸려 칸이 남으면 남은 칸은 점수순으로 채운다 — 소스가 하나뿐인 날 예산을 버리지 않는다.
 */
export const PER_SOURCE_ENRICH_LIMIT = 3;

/**
 * 주제 판정을 한 번에 몇 건까지 동시에 물어볼지.
 *
 * 순차로 돌리면 건당 3.8초(2026-08-12 실측: 70건 264초)라 소스 14곳의 첫 수집이 29분이 되고,
 * Vercel 함수 상한 300초에서 잘린다 — **에러 없이** 배열 앞쪽 소스만 적재되고 뒤쪽은 매일 빠진다.
 *
 * 무제한으로 던지지 않는 이유: 429(요청 과다)를 맞으면 판정이 실패하고, INV-F3 이 실패를
 * **통과**로 처리하므로 필터가 조용히 열린다. 거르라고 만든 장치가 몰아쳐서 안 거르게 되는 셈이다.
 */
export const TOPIC_CONCURRENCY = 8;

/**
 * 한 바퀴에 쓸 수 있는 시간 (INV-C4 의 시간 판).
 *
 * Vercel 함수 상한이 300초인데 단계가 전부 순차라 최악치가 그것을 넘는다
 * (피드 14곳×15초 + 판정 실측 125초 + 추출 10×15초 + 요약 10×30초). 넘기면 함수가 죽고
 * **응답 본문이 없다** — 이번에 만든 failureReasons·notChecked·토큰 계측이 제일 필요한 날
 * 하나도 안 남고, 요금만 나간 상태가 된다.
 *
 * 그래서 300 이 아니라 240 이다. 남은 60초는 리포트를 만들어 돌려주는 몫이다.
 * 예산이 떨어지면 그 단계를 **건너뛰고 리포트를 정상 반환한다** — 건너뛴 사실은 리포트에 남는다.
 */
export const INGEST_BUDGET_MS = 240_000;

/**
 * 외부 응답에서 받을 최대 바이트.
 *
 * 타임아웃(15초)만으로는 부족하다 — 15초 동안 수백 MB 를 흘려보내면 함수가 메모리로 죽고,
 * 그 뒤 JSDOM 파싱은 동기라 더 나쁘다. 실패한 항목은 `content_html` 이 빈 채 남아
 * 다음 주기에도 같은 자리에서 다시 잡히므로(백오프 없음) 매일 같은 곳에서 죽는다.
 */
export const MAX_FETCH_BYTES = 2_000_000;

